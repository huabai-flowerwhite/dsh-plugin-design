// dsh-plugin-design — client bundle builder
//
// Wraps src/client.js (a factory body) into the lazy-CJS artifact the harness
// client module system loads:
//
//   window.__ModuleLoader__.load({ id, factory: (require) => { ...模块体... } })
//
// Usage:
//   node scripts/build-client.mjs          # write lib/client.js
//   node scripts/build-client.mjs --check  # exit 1 when lib/client.js is stale
//
// The package publishes only built artifacts; tests call this module to prove
// src/ and lib/ never drift.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const SOURCE = join(root, 'src', 'client.js')
const TARGET = join(root, 'lib', 'client.js')

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

/** Indent every non-empty line of a factory body by `width` spaces. */
function indentBody(body, width) {
  const pad = ' '.repeat(width)
  return body
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : pad + line))
    .join('\n')
}

/** Render the complete lib/client.js content. */
export function renderClientBundle() {
  const pkg = readJson(join(root, 'package.json'))
  const source = readFileSync(SOURCE, 'utf8')
  const version = typeof pkg.version === 'string' ? pkg.version : '0.0.0'
  const harness = pkg.engines && typeof pkg.engines.dsh === 'string' ? pkg.engines.dsh : 'unknown'
  const body = source
    .replaceAll('__DSHPD_VERSION__', version)
    .replaceAll('__DSHPD_HARNESS__', harness)

  return [
    '// Generated by scripts/build-client.mjs from src/client.js — do not edit by hand.',
    '// Harness contract: window.__ModuleLoader__.load({ id, factory }) lazy-CJS module.',
    'window.__ModuleLoader__.load({',
    '  id: ' + JSON.stringify(pkg.name) + ',',
    '  factory: (require) => {',
    '    var module = { exports: {} };',
    '    var exports = module.exports;',
    indentBody(body, 4),
    '    return module.exports;',
    '  },',
    '});',
    '',
  ].join('\n')
}

/** Build the artifact. */
export function buildClient() {
  const rendered = renderClientBundle()
  mkdirSync(dirname(TARGET), { recursive: true })
  writeFileSync(TARGET, rendered, 'utf8')
  return { target: TARGET, bytes: Buffer.byteLength(rendered, 'utf8') }
}

/** Whether the checked-in artifact matches the current source. */
export function checkClient() {
  const rendered = renderClientBundle()
  if (!existsSync(TARGET)) return { ok: false, reason: 'lib/client.js is missing; run npm run build:client' }
  const current = readFileSync(TARGET, 'utf8')
  if (current === rendered) return { ok: true }
  return { ok: false, reason: 'lib/client.js is stale; run npm run build:client' }
}

const invokedDirectly = process.argv[1] !== undefined
  && import.meta.url === pathToFileURL(process.argv[1]).href

if (invokedDirectly) {
  if (process.argv.includes('--check')) {
    const result = checkClient()
    if (!result.ok) {
      console.error('[dsh-plugin-design] ' + result.reason)
      process.exitCode = 1
    } else {
      console.log('[dsh-plugin-design] lib/client.js is up to date')
    }
  } else {
    const result = buildClient()
    console.log('[dsh-plugin-design] wrote ' + result.target + ' (' + result.bytes + ' bytes)')
  }
}
